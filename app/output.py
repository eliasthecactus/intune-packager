RESTART = {"basedOnReturnCode": "Determine behavior based on return codes", "allow": "App install may force a device restart",
           "suppress": "No specific action", "force": "Intune will force a mandatory device restart"}
OPERATOR = {"equals": "Equals", "notEqual": "Not equal to", "greaterThan": "Greater than",
            "greaterThanOrEqual": "Greater than or equal to", "lessThan": "Less than", "lessThanOrEqual": "Less than or equal to"}
FILE_METHOD = {"exists": "File or folder exists", "doesNotExist": "File or folder does not exist", "version": "String (version)",
               "dateModified": "Date modified", "dateCreated": "Date created", "sizeInMB": "Size in MB"}
REG_METHOD = {"exists": "Key exists", "doesNotExist": "Key does not exist", "string": "String comparison",
              "integer": "Integer comparison", "version": "Version comparison"}
DEFAULT_CODES = [(0, "success"), (1707, "success"), (3010, "softReboot"), (1641, "hardReboot"), (1618, "retry")]


def safe_name(text: str) -> str:
    return re.sub(r"[^\w.\-]+", "-", text).strip("-.")[:60] or "app"


def _md_escape(text: str) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")


def _code(text: str) -> str:
    return f"`{text}`" if "`" not in text else f"``{text}``"


def _rule_md(i: int, rule: dict, L: dict, script_file: str | None) -> list[str]:
    t = rule.get("type")
    out = [f"**{L['rule']} {i}: {t.upper() if t else '?'}**", ""]
    rows: list[tuple[str, str]] = []
    if t == "msi":
        rows.append(("Product code", _code(rule.get("msi_product_code", ""))))
        if rule.get("msi_product_version"):
            rows.append(("Value / Product version check", f"{L['yes']} · {OPERATOR.get(rule.get('msi_version_operator') or 'greaterThanOrEqual')} · {_code(rule['msi_product_version'])}"))
        else:
            rows.append(("Product version check", L["no"]))
    elif t == "file":
        rows += [("Path", _code(rule.get("path", ""))), ("File or folder", _code(rule.get("file_or_folder", ""))),
                 ("Detection method", FILE_METHOD.get(rule.get("file_method", ""), rule.get("file_method", "")))]
        if rule.get("operator"):
            rows.append(("Operator", OPERATOR.get(rule["operator"], rule["operator"])))
        if rule.get("value"):
            rows.append(("Value", _code(rule["value"])))
        rows.append(("Associated with a 32-bit app on 64-bit clients", L["yes"] if rule.get("check_32bit_on_64bit") else L["no"]))
    elif t == "registry":
        rows += [("Key path", _code(rule.get("key_path", ""))), ("Value name", _code(rule.get("value_name") or "") if rule.get("value_name") else "–"),
                 ("Detection method", REG_METHOD.get(rule.get("registry_method", ""), rule.get("registry_method", "")))]
        if rule.get("operator"):
            rows.append(("Operator", OPERATOR.get(rule["operator"], rule["operator"])))
        if rule.get("value"):
            rows.append(("Value", _code(rule["value"])))
        rows.append(("Associated with a 32-bit app on 64-bit clients", L["yes"] if rule.get("check_32bit_on_64bit") else L["no"]))
    elif t == "script":
        rows += [("Script file", f"`{script_file}`" if script_file else "–"),
                 ("Run script as 32-bit process on 64-bit clients", L["yes"] if rule.get("run_as_32bit") else L["no"]),
                 ("Enforce script signature check", L["yes"] if rule.get("enforce_signature_check") else L["no"])]
    out += ["| | |", "|---|---|"] + [f"| {_md_escape(k)} | {_md_escape(v)} |" for k, v in rows] + [""]
    return out


def build_readme(r: dict, files: list[str], package_name: str | None, script_files: dict[int, str],
                 build_error: str | None = None) -> str:
    lang = (r.get("language") or "en").lower()[:2]
    L = LABELS.get(lang, LABELS["en"])
    app = r.get("app") or {}
    feasible = bool(r.get("feasible"))
    lines = [f"# {app.get('name') or L['title']}", ""]
    status = L["status_failed"] if build_error else (L["status_ok"] if feasible else L["status_no"])
    conf = r.get("confidence")
    lines += [f"**{status}**" + (f" · {L['confidence']}: {conf}" if conf else ""), "", f"> {L['review']}", ""]
    lines += [f"## {L['summary']}", "", r.get("summary", ""), ""]

    if feasible:
        lines += [f"## {L['app']}", "", "| | |", "|---|---|"]
        for key in ("name", "publisher", "version", "description"):
            if app.get(key):
                lines.append(f"| {L[key]} | {_md_escape(app[key])} |")
        for key, label in (("information_url", "Information URL"), ("privacy_url", "Privacy URL"), ("category", "Category")):
            if app.get(key):
                lines.append(f"| {label} | {_md_escape(app[key])} |")
        lines.append("")

        lines += [f"## {L['program']}", "", "| | |", "|---|---|"]
        if package_name:
            lines.append(f"| {L['package']} | `{package_name}` |")
        lines += [
            f"| {L['setup']} | `{r.get('setup_file', '')}` |",
            f"| {L['installer_type']} | {L['cmdline']} |",
            f"| {L['install']} | {_md_escape(_code(r.get('install_command', '')))} |",
            f"| {L['uninstall']} | {_md_escape(_code(r.get('uninstall_command', '')))} |",
            f"| {L['time']} | {r.get('max_install_minutes') or 60} |",
            f"| {L['avail_uninstall']} | {L['yes'] if r.get('allow_available_uninstall', True) else L['no']} |",
            f"| {L['behavior']} | {(r.get('install_behavior') or 'system').capitalize()} |",
            f"| {L['restart']} | {RESTART.get(r.get('device_restart_behavior') or 'basedOnReturnCode')} |",
            "",
        ]
        codes = r.get("return_codes") or [{"code": c, "type": t} for c, t in DEFAULT_CODES]
        lines += [f"**{L['return_codes']}:** " + ", ".join(f"{c['code']} = {c['type']}" for c in codes), ""]

        req = r.get("requirements") or {}
        lines += [f"## {L['requirements']}", "", "| | |", "|---|---|",
                  f"| {L['arch']} | {', '.join(req.get('architectures') or ['x64'])} |",
                  f"| {L['min_os']} | {req.get('minimum_os') or 'Windows 10 22H2'} |"]
        if req.get("disk_space_mb"):
            lines.append(f"| {L['disk']} | {req['disk_space_mb']} |")
        if req.get("memory_mb"):
            lines.append(f"| {L['memory']} | {req['memory_mb']} |")
        if req.get("requirement_script"):
            lines.append(f"| {L['req_script']} | `requirements/requirement.ps1` |")
        lines.append("")

        lines += [f"## {L['detection']}", ""]
        for i, rule in enumerate(r.get("detection_rules") or [], 1):
            lines += _rule_md(i, rule, L, script_files.get(i))

        if r.get("dependencies"):
            lines += [f"## {L['dependencies']}", ""] + [f"- {d}" for d in r["dependencies"]] + [""]

    for key, label in (("notes", "notes"), ("warnings", "warnings"), ("unknowns", "unknowns"), ("next_steps", "next")):
        items = r.get(key) or []
        if items:
            lines += [f"## {L[label]}", ""] + [f"- {x}" for x in items] + [""]

    lines += [f"## {L['files']}", ""] + [f"- `{f}`" for f in files] + [""]
    sources = r.get("sources") or []
    if sources:
        lines += [f"## {L['sources']}", ""] + [f"- [{s.get('title') or s['url']}]({s['url']})" for s in sources if s.get("url")] + [""]
    return "\n".join(lines)


def build_deliverable(result: dict, source: Path, output: Path, logo: Path | None, job_id: str) -> tuple[Path, dict]:
    """Create all output files and the zip. Returns (zip_path, summary_for_ui)."""
    app_name = (result.get("app") or {}).get("name") or "intune-app"
    folder = safe_name(app_name)
    out_dir = output / folder
    out_dir.mkdir(parents=True, exist_ok=True)
    files: list[str] = []
    package_name = None
    build_error = None

    if result.get("feasible"):
        setup = (result.get("setup_file") or "").replace("\\", "/").removeprefix("source/")
        result["setup_file"] = setup
        version = (result.get("app") or {}).get("version")
        package_name = safe_name(f"{app_name}-{version}" if version else app_name) + ".intunewin"
        try:
            build_intunewin(source, setup, out_dir / package_name)
            files.append(package_name)
        except Exception as exc:
            build_error = str(exc)
            package_name = None
            result.setdefault("warnings", []).insert(0, f"Packaging failed: {exc}")

        # copy generated scripts/configs (small text files) for review
        for p in sorted(source.rglob("*")):
            if p.is_file() and p.suffix.lower() in (".ps1", ".bat", ".cmd", ".json", ".xml", ".ini", ".properties", ".reg", ".txt", ".iss", ".cfg") \
                    and p.stat().st_size < 1024 * 1024:
                rel = p.relative_to(source)
                dst = out_dir / "package-scripts" / rel
                dst.parent.mkdir(parents=True, exist_ok=True)
                dst.write_bytes(p.read_bytes())
                files.append(f"package-scripts/{rel.as_posix()}")

    script_files: dict[int, str] = {}
    for i, rule in enumerate(result.get("detection_rules") or [], 1):
        if rule.get("type") == "script" and rule.get("script_content"):
            name = "detection/detect.ps1" if not script_files else f"detection/detect-{len(script_files) + 1}.ps1"
            p = out_dir / name
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_bytes(rule["script_content"].replace("\r\n", "\n").replace("\n", "\r\n").encode("utf-8-sig"))
            script_files[i] = name
            files.append(name)
    req_script = (result.get("requirements") or {}).get("requirement_script")
    if req_script:
        p = out_dir / "requirements" / "requirement.ps1"
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_bytes(req_script.replace("\r\n", "\n").replace("\n", "\r\n").encode("utf-8-sig"))
        files.append("requirements/requirement.ps1")

    if logo and logo.is_file():
        (out_dir / "logo.png").write_bytes(logo.read_bytes())
        files.append("logo.png")

    files += ["intune-app.json", "README.md"]
    (out_dir / "intune-app.json").write_text(json.dumps(result, indent=2, ensure_ascii=False), encoding="utf-8")
    readme = build_readme(result, files, package_name, script_files, build_error)
    (out_dir / "README.md").write_text(readme, encoding="utf-8")

    zip_path = output / f"{folder}.zip"
    with zipfile.ZipFile(zip_path, "w", zipfile.ZIP_DEFLATED, allowZip64=True) as zf:
        for p in sorted(out_dir.rglob("*")):
            if p.is_file():
                # .intunewin is encrypted - compressing it only costs time
                ctype = zipfile.ZIP_STORED if p.suffix == ".intunewin" else zipfile.ZIP_DEFLATED
                zf.write(p, f"{folder}/{p.relative_to(out_dir).as_posix()}", compress_type=ctype)

    ui = {
        "feasible": bool(result.get("feasible")) and not build_error,
        "readme": readme,
        "result": result,
        "files": files,
        "zip_name": zip_path.name,
        "logo": "logo.png" in files,
        "folder": folder,
    }
    return zip_path, ui
